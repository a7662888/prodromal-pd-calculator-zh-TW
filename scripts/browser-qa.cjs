// Local, synthetic-input QA. No real health information. Requires installed Playwright.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const target = process.argv[2] || 'http://127.0.0.1:8791/';
const out = process.argv[3] || 'qa';
(async () => {
  await fs.mkdir(out,{recursive:true});
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  const context = await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>requests.push({url:r.url(),method:r.method()}));
  const response = await page.goto(target);
  assert.equal(response.status(),200);
  await page.waitForFunction(()=>document.querySelectorAll('#marker-groups select').length===22);
  assert.equal(await page.locator('#probability').innerText(),'—');
  await page.locator('#example').click();
  assert.equal(await page.locator('#probability').innerText(),'92.55');
  assert.match(await page.locator('#result-label').innerText(),/符合 probable/);
  await page.screenshot({path:`${out}/desktop.png`});
  const requestCountAfterLoad = requests.length;
  await page.locator('#sex').selectOption('female');
  assert.equal(await page.locator('#urate').isDisabled(),true);
  assert.equal(await page.locator('#erectile').isDisabled(),true);
  assert.equal(await page.locator('#example-note').isVisible(),false);
  await page.locator('#clinicalPD').selectOption('yes');
  assert.equal(await page.locator('#probability').innerText(),'—');
  await page.locator('#reset').click();
  assert.equal(await page.locator('#age').inputValue(),'');
  assert.equal(await page.locator('#rbd').inputValue(),'unknown');
  await page.locator('#age').selectOption('65');
  await page.locator('#clinicalPD').selectOption('no');
  await page.locator('#highPenetrance').selectOption('no');
  assert.equal(await page.locator('#probability').innerText(),'2.00');
  await page.locator('#sex').selectOption('male');
  await page.locator('#rbd').selectOption('psgYes');
  assert.equal(await page.locator('#probability').innerText(),'76.10');
  await page.locator('#olfaction').selectOption('yes');
  assert.equal(await page.locator('#probability').innerText(),'95.32');
  await page.locator('#age').selectOption('under50');
  assert.equal(await page.locator('#probability').innerText(),'—');
  await page.locator('#age').selectOption('65');
  await page.locator('#highPenetrance').selectOption('yes');
  assert.equal(await page.locator('#probability').innerText(),'—');
  await page.locator('#example').click();
  assert.equal(requests.length,requestCountAfterLoad,'Input events must cause zero requests');
  assert.equal(requests.some(r=>r.method!=='GET'),false);
  assert.equal(requests.some(r=>new URL(r.url).origin!==new URL(target).origin),false);
  const storage = await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length,cookie:document.cookie,serviceWorker:!!navigator.serviceWorker?.controller}));
  assert.deepEqual(storage,{local:0,session:0,cookie:'',serviceWorker:false});
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('#marker-groups select').length===22);
  await page.locator('#example').click();
  assert.equal(await page.locator('.audit-panel').getAttribute('open'),null);
  await page.screenshot({path:`${out}/mobile-top.png`});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile horizontal overflow');
  await page.locator('#eligibility-title').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${out}/mobile-form.png`});
  await page.setViewportSize({width:320,height:740});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'320px horizontal overflow');
  await page.screenshot({path:`${out}/mobile-320.png`});
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('#marker-groups select').length===22);
  assert.equal(await page.locator('#age').inputValue(),'');
  assert.equal(await page.locator('#probability').innerText(),'—');
  assert.deepEqual(errors,[]);
  const report = {target,checkedAt:new Date().toISOString(),status:'PASS',checks:['calculator tests executed separately','synthetic example 92.55%','independent reference cases 76.10% and 95.32%','male-only marker exclusion','eligibility guards','unknown-not-negative','reset/reload clearing','zero requests from input interactions','same-origin GET assets only','no cookie/storage/service worker','390px and 320px no horizontal overflow','no uncaught JavaScript errors'],storage,headers:response.headers(),requests};
  await fs.writeFile(`${out}/browser-qa.json`,JSON.stringify(report,null,2));
  console.log(JSON.stringify({status:report.status,target,checks:report.checks,assetRequests:requests.length}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
